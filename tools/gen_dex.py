#!/usr/bin/env python3
"""Generates dex.h (the Pokedex table for the firmware) from dex_data.py.

  python3 tools/gen_dex.py
"""
#region Imports
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(__file__))
from dex_data import DEX, TYPE_ACCENTS, BATTLE_TYPES, CLASSIC, RARE, LEGENDARY
from dex_stats import BASE_STATS
from dex_names import LOCAL_NAMES
#endregion

#region Configuration

# background biome by type (the lighting comes from the real RTC time)
# 0 MEADOW, 1 BEACH, 2 FOREST, 3 VOLCANO, 4 MOUNTAIN, 5 SNOW
TYPE_BIOME = {
    'agua': 1, 'planta': 2, 'bicho': 2, 'fuego': 3,
    'roca': 4, 'tierra': 4, 'dragon': 1, 'hielo': 5,  # gen1 dragons (Dratini) live in the water
    'normal': 0, 'electrico': 0, 'lucha': 0, 'veneno': 0,
    'psiquico': 0, 'fantasma': 0,
}

# per-dex# exceptions (the type is not enough): marine rock/water fossils -> beach
BIOME_OVERRIDE = {138: 1, 139: 1, 140: 1, 141: 1}  # Omanyte, Omastar, Kabuto, Kabutops

# battle types in the order of the dex.h TYPE_* enum (TYPE_NONE = 0 comes first)
BATTLE_TYPE_ORDER = (
    'normal', 'fire', 'water', 'electric', 'grass',
    'ice', 'fighting', 'poison', 'ground', 'flying', 'psychic',
    'bug', 'rock', 'ghost', 'dragon', 'dark', 'steel', 'fairy',
)

#endregion

#region Internal helpers

def convert_hex_color_to_rgb565(hex_color):
    red = int(hex_color[1:3], 16)
    green = int(hex_color[3:5], 16)
    blue = int(hex_color[5:7], 16)
    return (red >> 3) << 11 | (green >> 2) << 5 | (blue >> 3)


def convert_battle_type_to_enum_name(battle_type):
    if battle_type is None:
        return 'TYPE_NONE'
    if battle_type not in BATTLE_TYPE_ORDER:
        raise ValueError(f"unknown battle type: {battle_type!r}")
    return f"TYPE_{battle_type.upper()}"


def validate_battle_types_cover_dex():
    #region Every species needs a primary battle type
    missing_species = [species_number for species_number, *_ in DEX
                       if species_number not in BATTLE_TYPES]
    if missing_species:
        raise ValueError(f"BATTLE_TYPES has no entry for dex numbers: {missing_species}")
    for species_number, *_ in DEX:
        primary_type, secondary_type = BATTLE_TYPES[species_number]
        if primary_type is None:
            raise ValueError(f"BATTLE_TYPES[{species_number}] has no primary type")
        convert_battle_type_to_enum_name(primary_type)
        convert_battle_type_to_enum_name(secondary_type)
    #endregion

#endregion

#region Public API

def build_dex_header_text():
    """Returns (dex.h text, rarity counter). Does not write anything."""
    validate_battle_types_cover_dex()
    out = []

    #region Header, constants and DexEntry struct
    out.append("#pragma once\n#include <stdint.h>\n#include \"i18n.h\"  // gLang\n\n")
    out.append("// GENERATED by tools/gen_dex.py from tools/dex_data.py - do not edit\n\n")
    out.append("#define DEX_COUNT 151\n")
    out.append("#define DEX_EEVEE 133  // random branch: 134/135/136\n")
    out.append("#define DEX_BITMAP_BYTES ((DEX_COUNT + 7) / 8)  // one bit per species\n\n")
    out.append(
        "// rarity: 0 = evolution only, 1 = common, 2 = rare, 3 = legendary\n"
        "enum : uint8_t { R_EVO = 0, R_COMUN, R_RARO, R_LEGENDARIO };\n\n")
    out.append(
        "// battle types (modern chart)\n"
        "enum : uint8_t {\n"
        "  TYPE_NONE = 0, TYPE_NORMAL, TYPE_FIRE, TYPE_WATER, TYPE_ELECTRIC, TYPE_GRASS,\n"
        "  TYPE_ICE, TYPE_FIGHTING, TYPE_POISON, TYPE_GROUND, TYPE_FLYING, TYPE_PSYCHIC,\n"
        "  TYPE_BUG, TYPE_ROCK, TYPE_GHOST, TYPE_DRAGON, TYPE_DARK, TYPE_STEEL, TYPE_FAIRY,\n"
        "  TYPE_COUNT\n"
        "};\n\n")
    out.append(
        "struct DexEntry {\n"
        "  const char *name;\n"
        "  uint8_t evolvesTo;    // dex number, 0 = final form\n"
        "  uint8_t evolveLevel;\n"
        "  uint8_t rarity;       // hatches from an egg if > 0\n"
        "  uint16_t accent;      // type's RGB565 color for the UI\n"
        "  uint8_t bHp, bAtk, bDef, bSpe;  // real gen 1 base stats\n"
        "  uint8_t type1, type2;  // battle types (modern chart), TYPE_NONE if no secondary\n"
        "  uint8_t biome;        // 0 meadow 1 beach 2 forest 3 volcano 4 mountain 5 snow\n"
        "};\n\n")
    #endregion

    #region DEX_TBL
    # base forms = those that are nobody's evolution (the Eevee branches are)
    evolved_species = {entry[4] for entry in DEX if entry[4]} | {135, 136}
    rarities = []
    out.append("static const DexEntry DEX_TBL[DEX_COUNT + 1] = {\n")
    out.append('  { "?", 0, 0, 0, 0x2946, 50, 50, 50, 50, TYPE_NONE, TYPE_NONE, 0 },  // 0: unused\n')
    for species_number, _slug, display_name, accent_type, evolves_to, evolve_level in DEX:
        accent_color = convert_hex_color_to_rgb565(TYPE_ACCENTS[accent_type])
        if species_number in evolved_species:
            rarity_name = 'R_EVO'
        elif species_number in LEGENDARY:
            rarity_name = 'R_LEGENDARIO'
        elif species_number in RARE:
            rarity_name = 'R_RARO'
        else:
            rarity_name = 'R_COMUN'
        rarities.append(rarity_name)
        base_hp, base_attack, base_defense, base_speed = BASE_STATS[species_number]
        primary_type, secondary_type = BATTLE_TYPES[species_number]
        type1_name = convert_battle_type_to_enum_name(primary_type)
        type2_name = convert_battle_type_to_enum_name(secondary_type)
        biome = BIOME_OVERRIDE.get(species_number, TYPE_BIOME[accent_type])
        out.append(f'  {{ "{display_name}", {evolves_to}, {evolve_level}, {rarity_name}, '
                   f'0x{accent_color:04X}, {base_hp}, {base_attack}, {base_defense}, {base_speed}, '
                   f'{type1_name}, {type2_name}, {biome} }},  // {species_number} {accent_type}\n')
    out.append("};\n\n")
    #endregion

    #region Localized name tables
    # Only FR and DE have their own names in gen 1; ES/IT/PT use the English one.
    out.append(
        "// Official names per language. FR and DE are the only Latin-script ones that\n"
        "// differ from English in gen 1 (ES/IT/PT use the DEX_TBL one); JA and KO are\n"
        "// UTF-8, drawn with the U8g2 font. nullptr = no name of its own.\n")
    for language_code in ('fr', 'de', 'ja', 'ko'):
        out.append(f"static const char *const DEX_NAME_{language_code.upper()}[DEX_COUNT + 1] = {{\n")
        row_items = []
        for species_number in range(0, 152):
            local_name = LOCAL_NAMES.get(species_number, {}).get(language_code)
            row_items.append(f'"{local_name}"' if local_name else 'nullptr')
            if len(row_items) == 4:
                out.append("  " + ", ".join(row_items) + ",\n")
                row_items = []
        if row_items:
            out.append("  " + ", ".join(row_items) + ",\n")
        out.append("};\n\n")
    out.append(
        "// Species name in the active language (falls back to DEX_TBL if that\n"
        "// language has no name of its own for it).\n"
        "static inline const char *dexName(int16_t dex) {\n"
        "  if (dex < 1 || dex > DEX_COUNT) return DEX_TBL[0].name;\n"
        "  const char *n = (gLang == LANG_FR)   ? DEX_NAME_FR[dex]\n"
        "                  : (gLang == LANG_DE) ? DEX_NAME_DE[dex]\n"
        "                  : (gLang == LANG_JA) ? DEX_NAME_JA[dex]\n"
        "                  : (gLang == LANG_KO) ? DEX_NAME_KO[dex]\n"
        "                                       : nullptr;\n"
        "  return n ? n : DEX_TBL[dex].name;\n"
        "}\n\n")
    #endregion

    #region Classic starters
    out.append("// the first egg of the game: classic starters\n")
    out.append("static const int16_t CLASSIC_DEX[] = { %s };\n" % ", ".join(map(str, CLASSIC)))
    out.append(f"#define NUM_CLASSIC_DEX {len(CLASSIC)}\n")
    #endregion

    return ''.join(out), Counter(rarities)


def main():
    header_text, rarity_counter = build_dex_header_text()
    print(f"bases: {rarity_counter['R_COMUN']} common, {rarity_counter['R_RARO']} rare, "
          f"{rarity_counter['R_LEGENDARIO']} legendary, {rarity_counter['R_EVO']} evolution only")

    #region Write dex.h
    output_path = os.path.join(os.path.dirname(__file__), '..', 'dex.h')
    with open(output_path, 'w', encoding='utf-8') as output_file:
        output_file.write(header_text)
    print(f"saved {os.path.normpath(output_path)} ({len(DEX)} species)")
    #endregion


if __name__ == '__main__':
    main()

#endregion
