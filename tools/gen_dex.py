#!/usr/bin/env python3
"""Generates dex.h (the Pokedex table for the firmware) from dex_data.py.

  python3 tools/gen_dex.py

The tables are `inline constexpr` (C++17): every translation unit that
includes dex.h shares ONE copy in flash instead of one static copy each.
"""
#region Imports
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dex_data import DEX, TYPE_ACCENTS, BATTLE_TYPES, CLASSIC, RARE, LEGENDARY
from dex_stats import BASE_STATS
from dex_names import LOCAL_NAMES
from tamapoke_common import REPO_ROOT, hex_to_rgb565, write_generated_text
#endregion

#region Configuration

# background biomes, in the order of the dex.h Biome enum (ids 0..5)
# (the lighting comes from the real RTC time)
BIOME_NAMES = ('MEADOW', 'BEACH', 'FOREST', 'VOLCANO', 'MOUNTAIN', 'SNOW')

# background biome by accent type
TYPE_BIOME = {
    'water': 'BEACH', 'grass': 'FOREST', 'bug': 'FOREST', 'fire': 'VOLCANO',
    'rock': 'MOUNTAIN', 'ground': 'MOUNTAIN', 'dragon': 'BEACH', 'ice': 'SNOW',  # gen1 dragons (Dratini) live in the water
    'normal': 'MEADOW', 'electric': 'MEADOW', 'fighting': 'MEADOW', 'poison': 'MEADOW',
    'psychic': 'MEADOW', 'ghost': 'MEADOW',
}

# per-dex# exceptions (the type is not enough): marine rock/water fossils -> beach
BIOME_OVERRIDE = {138: 'BEACH', 139: 'BEACH', 140: 'BEACH', 141: 'BEACH'}  # Omanyte, Omastar, Kabuto, Kabutops

# battle types in the order of the dex.h TYPE_* enum (TYPE_NONE = 0 comes first)
BATTLE_TYPE_ORDER = (
    'normal', 'fire', 'water', 'electric', 'grass',
    'ice', 'fighting', 'poison', 'ground', 'flying', 'psychic',
    'bug', 'rock', 'ghost', 'dragon', 'dark', 'steel', 'fairy',
)

# Eevee evolves at random into one of these (game code, not the table)
EEVEE_DEX_NUMBER = 133
EEVEE_BRANCHES = (134, 135, 136)

# accent of the unused entry 0: the same ink color as UI_INK in species.h
UNUSED_ENTRY_ACCENT_HEX = '#2a2a36'

# languages with their own name table, in dexName() order
LOCAL_NAME_LANGUAGES = ('fr', 'de', 'ja', 'ko')

#endregion

#region Internal helpers

def convert_battle_type_to_enum_name(battle_type):
    if battle_type is None:
        return 'TYPE_NONE'
    if battle_type not in BATTLE_TYPE_ORDER:
        raise ValueError(f"unknown battle type: {battle_type!r}")
    return f"TYPE_{battle_type.upper()}"


def validate_battle_types_cover_dex():
    #region Every species needs a primary battle type
    missing_species = [species_number for species_number, *_ in DEX
                       if species_number not in BATTLE_TYPES]
    if missing_species:
        raise ValueError(f"BATTLE_TYPES has no entry for dex numbers: {missing_species}")
    for species_number, *_ in DEX:
        primary_type, secondary_type = BATTLE_TYPES[species_number]
        if primary_type is None:
            raise ValueError(f"BATTLE_TYPES[{species_number}] has no primary type")
        convert_battle_type_to_enum_name(primary_type)
        convert_battle_type_to_enum_name(secondary_type)
    #endregion


def pick_rarity_enum_name(species_number, evolved_species):
    if species_number in evolved_species:
        return 'R_EVO'
    if species_number in LEGENDARY:
        return 'R_LEGENDARY'
    if species_number in RARE:
        return 'R_RARE'
    return 'R_COMMON'

#endregion

#region Public API

def build_dex_header_text():
    """Returns (dex.h text, rarity counter). Does not write anything."""
    validate_battle_types_cover_dex()
    eevee_first_branch, eevee_last_branch = EEVEE_BRANCHES[0], EEVEE_BRANCHES[-1]
    out = []

    #region Includes and constants
    out.append("#pragma once\n\n#pragma region Includes\n#include <stdint.h>\n"
               "#include \"i18n.h\"  // gLang\n#pragma endregion\n\n")
    out.append("// GENERATED by tools/gen_dex.py from tools/dex_data.py - do not edit\n\n")
    out.append("#pragma region Constants\n")
    out.append(f"#define DEX_COUNT {len(DEX)}\n")
    out.append(f"#define DEX_EEVEE {EEVEE_DEX_NUMBER}  // random branch: "
               "DEX_EEVEE_FIRST_BRANCH..DEX_EEVEE_LAST_BRANCH\n")
    out.append(f"#define DEX_EEVEE_FIRST_BRANCH {eevee_first_branch}\n")
    out.append(f"#define DEX_EEVEE_LAST_BRANCH {eevee_last_branch}\n")
    out.append("#define DEX_BITMAP_BYTES ((DEX_COUNT + 7) / 8)  // one bit per species\n")
    out.append(f"#define DEX_UNUSED_ACCENT 0x{hex_to_rgb565(UNUSED_ENTRY_ACCENT_HEX):04X}  "
               f"// {UNUSED_ENTRY_ACCENT_HEX}, entry 0 (same color as UI_INK)\n")
    out.append("#pragma endregion\n\n")
    #endregion

    #region Enums and DexEntry struct
    out.append("#pragma region Enums\n")
    out.append(
        "// rarity: 0 = evolution only, 1 = common, 2 = rare, 3 = legendary\n"
        "enum : uint8_t { R_EVO = 0, R_COMMON, R_RARE, R_LEGENDARY };\n\n")
    out.append(
        "// battle types (modern chart)\n"
        "enum : uint8_t {\n"
        "  TYPE_NONE = 0, TYPE_NORMAL, TYPE_FIRE, TYPE_WATER, TYPE_ELECTRIC, TYPE_GRASS,\n"
        "  TYPE_ICE, TYPE_FIGHTING, TYPE_POISON, TYPE_GROUND, TYPE_FLYING, TYPE_PSYCHIC,\n"
        "  TYPE_BUG, TYPE_ROCK, TYPE_GHOST, TYPE_DRAGON, TYPE_DARK, TYPE_STEEL, TYPE_FAIRY,\n"
        "  TYPE_COUNT\n"
        "};\n\n")
    biome_enumerators = ', '.join(
        f"BIOME_{biome_name}{' = 0' if biome_index == 0 else ''}"
        for biome_index, biome_name in enumerate(BIOME_NAMES))
    out.append(
        "// background biome (the lighting comes from the real RTC time)\n"
        f"enum Biome : uint8_t {{ {biome_enumerators}, BIOME_COUNT }};\n")
    out.append("#pragma endregion\n\n")
    out.append(
        "#pragma region DexEntry\n"
        "struct DexEntry {\n"
        "  const char *name;\n"
        "  uint8_t evolvesTo;    // dex number, 0 = final form\n"
        "  uint8_t evolveLevel;\n"
        "  uint8_t rarity;       // hatches from an egg if > 0\n"
        "  uint16_t accent;      // type's RGB565 color for the UI\n"
        "  uint8_t bHp, bAtk, bDef, bSpe;  // real gen 1 base stats\n"
        "  uint8_t type1, type2;  // battle types (modern chart), TYPE_NONE if no secondary\n"
        "  uint8_t biome;        // Biome\n"
        "};\n"
        "#pragma endregion\n\n")
    #endregion

    #region DEX_TBL
    # base forms = those that are nobody's evolution (the Eevee branches are)
    evolved_species = {entry[4] for entry in DEX if entry[4]} | set(EEVEE_BRANCHES)
    rarities = []
    out.append("#pragma region DEX_TBL\n")
    out.append("inline constexpr DexEntry DEX_TBL[DEX_COUNT + 1] = {\n")
    out.append('  { "?", 0, 0, R_EVO, DEX_UNUSED_ACCENT, 50, 50, 50, 50, TYPE_NONE, TYPE_NONE, '
               'BIOME_MEADOW },  // 0: unused\n')
    for species_number, _slug, display_name, accent_type, evolves_to, evolve_level in DEX:
        accent_color = hex_to_rgb565(TYPE_ACCENTS[accent_type])
        rarity_name = pick_rarity_enum_name(species_number, evolved_species)
        rarities.append(rarity_name)
        base_hp, base_attack, base_defense, base_speed = BASE_STATS[species_number]
        primary_type, secondary_type = BATTLE_TYPES[species_number]
        type1_name = convert_battle_type_to_enum_name(primary_type)
        type2_name = convert_battle_type_to_enum_name(secondary_type)
        biome_name = BIOME_OVERRIDE.get(species_number, TYPE_BIOME[accent_type])
        out.append(f'  {{ "{display_name}", {evolves_to}, {evolve_level}, {rarity_name}, '
                   f'0x{accent_color:04X}, {base_hp}, {base_attack}, {base_defense}, {base_speed}, '
                   f'{type1_name}, {type2_name}, BIOME_{biome_name} }},  '
                   f'// {species_number} {accent_type}\n')
    out.append("};\n#pragma endregion\n\n")
    #endregion

    #region Localized name tables
    # Only FR and DE have their own Latin-script names in gen 1; ES/IT/PT use the English one.
    out.append("#pragma region Localized names\n")
    out.append(
        "// Official names per language. FR and DE are the only Latin-script ones that\n"
        "// differ from English in gen 1 (ES/IT/PT use the DEX_TBL one); JA and KO are\n"
        "// UTF-8, drawn with the U8g2 font. nullptr = no name of its own.\n")
    for language_code in LOCAL_NAME_LANGUAGES:
        out.append(f"inline constexpr const char *DEX_NAME_{language_code.upper()}[DEX_COUNT + 1] = {{\n")
        row_items = []
        for species_number in range(0, len(DEX) + 1):
            local_name = LOCAL_NAMES.get(species_number, {}).get(language_code)
            row_items.append(f'"{local_name}"' if local_name else 'nullptr')
            if len(row_items) == 4:
                out.append("  " + ", ".join(row_items) + ",\n")
                row_items = []
        if row_items:
            out.append("  " + ", ".join(row_items) + ",\n")
        out.append("};\n\n")
    out.append(
        "// Species name in the active language (falls back to DEX_TBL if that\n"
        "// language has no name of its own for it).\n"
        "inline const char *dexName(int16_t dex) {\n"
        "  if (dex < 1 || dex > DEX_COUNT) return DEX_TBL[0].name;\n"
        "  const char *localName = (gLang == LANG_FR)   ? DEX_NAME_FR[dex]\n"
        "                          : (gLang == LANG_DE) ? DEX_NAME_DE[dex]\n"
        "                          : (gLang == LANG_JA) ? DEX_NAME_JA[dex]\n"
        "                          : (gLang == LANG_KO) ? DEX_NAME_KO[dex]\n"
        "                                               : nullptr;\n"
        "  return localName ? localName : DEX_TBL[dex].name;\n"
        "}\n"
        "#pragma endregion\n\n")
    #endregion

    #region Classic starters
    out.append("#pragma region Classic starters\n")
    out.append("// the first egg of the game: classic starters\n")
    out.append("inline constexpr int16_t CLASSIC_DEX[] = { %s };\n" % ", ".join(map(str, CLASSIC)))
    out.append("#define NUM_CLASSIC_DEX ((int)(sizeof(CLASSIC_DEX) / sizeof(CLASSIC_DEX[0])))\n")
    out.append("#pragma endregion\n")
    #endregion

    return ''.join(out), Counter(rarities)


def main():
    header_text, rarity_counter = build_dex_header_text()
    print(f"bases: {rarity_counter['R_COMMON']} common, {rarity_counter['R_RARE']} rare, "
          f"{rarity_counter['R_LEGENDARY']} legendary, {rarity_counter['R_EVO']} evolution only")

    #region Write dex.h
    output_path = os.path.join(REPO_ROOT, 'dex.h')
    write_generated_text(output_path, header_text)
    print(f"saved {os.path.normpath(output_path)} ({len(DEX)} species)")
    #endregion


if __name__ == '__main__':
    main()

#endregion
